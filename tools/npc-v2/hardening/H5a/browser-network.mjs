import { chromium } from '../../../node_modules/playwright/index.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { randomUUID, createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const here = new URL('./', import.meta.url);
const env = Object.fromEntries(readFileSync(new URL('.env.local', here), 'utf8').trim().split('\n').map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
Object.assign(env, Object.fromEntries(['H5_ORIGIN', 'H5_HARNESS_TOKEN', 'H5_RUNTIME_TOKEN'].filter(key => process.env[key]).map(key => [key, process.env[key]])));
const base = env.H5_ORIGIN;
const headers = { Authorization: `Bearer ${env.H5_HARNESS_TOKEN}` };
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const id = `network-${Date.now()}-${randomUUID()}`;
mkdirSync(new URL('evidence/', here), { recursive: true });
const output = new URL(`evidence/${id}.json`, here);
const evidence = { status: 'blocked', base, runId: id, rows: [], errors: [], websocket: [], hashes: [], sources: Object.fromEntries(['adapter.ts', 'dispatch-time.ts', 'wire.ts', 'server.py', 'broker.py', 'browser-network.mjs', 'dist/adapter.js'].map(file => [file, sha(readFileSync(new URL(file, here)))])) };
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-dev-shm-usage'] });
let page;
try {
  page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  page.on('pageerror', e => evidence.errors.push(String(e)));
  page.on('websocket', ws => evidence.websocket.push({ url: ws.url(), realWebSocket: true }));
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Network.enable');
  cdp.on('Network.webSocketHandshakeResponseReceived', event => evidence.websocket.push({ handshakeStatus: event.response.status, requestId: event.requestId }));
  for (const file of ['npc-h4b.html', 'harness-preview/app.js', 'harness-preview/h4b-app.js', 'harness-preview/scene-app.js', 'harness-preview/npc-h4a-core.js', 'harness-preview/npc-h4a-worker.js']) {
    const response = await page.request.get(`${base}/room/web/${file}`);
    assert.equal(response.status(), 200, file);
    evidence.hashes.push({ file, sha256: sha(await response.body()) });
  }
  await page.goto(base);
  await page.waitForFunction(() => window.__h5?.ready, null, { timeout: 90000 });
  await page.evaluate(() => { window.__h5.setManual(true); window.__h5.setRender(false); });
  await page.fill('#credential', env.H5_RUNTIME_TOKEN);
  await page.click('#connect');
  await page.waitForFunction(() => window.__h5.connected(), null, { timeout: 10000 });
  const scope = await page.evaluate(() => window.__h5.scope());
  const read = async path => { const r = await page.request.get(base + '/api/h5a/' + path, { headers }); return { status: r.status(), body: await r.json() }; };
  const post = async (path, data) => { const r = await page.request.post(base + '/api/h5a/' + path, { headers, data }); return { status: r.status(), body: await r.json() }; };
  const sample = async name => { const row = { name, status: await read('status'), browser: await page.evaluate(() => ({ snapshot: window.__h5.snapshot(), diagnostics: window.__h5.diagnostics(), trace: window.__h5.trace() })) }; evidence.rows.push(row); return row; };
  const step = seconds => page.evaluate(seconds => window.__h5.step(seconds), seconds);
  const waitReceipt = async (commandId, status) => {
    await page.waitForFunction(({ commandId, status }) => window.__h5.trace().some(t => t.commandId === commandId && (t.status === status || t.status === 'rejected' || t.status === 'failed')) || !window.__h5.connected(), { commandId, status }, { timeout: 10000 });
    await page.waitForFunction(() => window.__h5.pendingReports() === 0, null, { timeout: 10000 });
    const result = await read('commands/' + commandId);
    assert.equal(result.body.status, status, JSON.stringify(result.body)); return result;
  };
  evidence.capabilities = await read('capabilities'); assert.equal(evidence.capabilities.body.available, true);
  const command = { apiVersion: 'h5a.1', scope, commandId: id + '-look', type: 'action.request', actionKey: 'lookAround', issuedAtWallMs: Date.now(), ttlMs: 60000 };
  evidence.post = await post('commands', command); assert.equal(evidence.post.status, 202); assert.equal(evidence.post.body.execution, null);
  evidence.accepted = await waitReceipt(command.commandId, 'accepted');
  evidence.duplicateAccepted = await post('commands', command);
  assert.deepEqual(evidence.duplicateAccepted.body, evidence.accepted.body);
  await step(.1);
  evidence.started = await waitReceipt(command.commandId, 'started');
  const running = await sample('real-started');
  assert.equal(running.browser.diagnostics.runtime.action.actionKey, 'lookAround');
  assert.equal(running.browser.diagnostics.runtime.action.actionId, evidence.started.body.actionId);
  assert.equal(running.browser.diagnostics.runtime.action.attemptId, evidence.started.body.attemptId);
  evidence.duplicateStarted = await post('commands', command);
  assert.deepEqual(evidence.duplicateStarted.body, evidence.started.body);
  const attempt = evidence.started.body.attemptId;
  assert(attempt);
  await step(1.4);
  evidence.terminal = await waitReceipt(command.commandId, 'succeeded');
  assert.equal(evidence.terminal.body.terminal.attemptId, attempt);
  const completed = await sample('real-terminal');
  assert(completed.browser.diagnostics.terminals.some(t => t.actionId === evidence.terminal.body.actionId && t.attemptId === attempt && t.outcome === 'success'));
  evidence.lifecycle = completed.browser.trace.filter(t => t.commandId === command.commandId).map(t => t.status);
  assert.deepEqual(evidence.lifecycle, ['accepted', 'started', 'succeeded']);
  const beginCount = completed.browser.diagnostics.calls.filter(c => c.method === 'begin').length;
  evidence.duplicate = await post('commands', command); assert.equal(evidence.duplicate.body.attemptId, attempt);
  await step(.2);
  const duplicate = await sample('duplicate-no-new-attempt');
  assert.equal(duplicate.browser.diagnostics.terminals.filter(t => t.actionKey === 'lookAround' && t.goalId === 'single-action').length, 1);
  assert.equal(duplicate.browser.diagnostics.calls.filter(c => c.method === 'begin').length, beginCount);
  evidence.conflict = await post('commands', { ...command, ttlMs: 50000 }); assert.equal(evidence.conflict.status, 409);
  evidence.invalid = await post('commands', { ...command, commandId: id + '-invalid', pose: {} }); assert.equal(evidence.invalid.status, 400);
  evidence.unsupportedAction = await post('commands', { ...command, commandId: id + '-unknown', actionKey: 'standUp' }); assert.equal(evidence.unsupportedAction.status, 422);
  evidence.expired = await post('commands', { ...command, commandId: id + '-expired', issuedAtWallMs: Date.now() - 2000, ttlMs: 1000 }); assert.equal(evidence.expired.status, 410);
  evidence.oldEpoch = await post('commands', { ...command, commandId: id + '-old-epoch', scope: { ...scope, authorityEpoch: 'old-authority' } });
  assert.equal(evidence.oldEpoch.status, 409); assert.equal(evidence.oldEpoch.body.code, 'STALE_AUTHORITY_EPOCH');
  // A received-but-not-stepped command must still expire on real wall time.
  const pausedExpiry = { ...command, commandId: id + '-paused-expiry', issuedAtWallMs: Date.now(), ttlMs: 1000 };
  await post('commands', pausedExpiry); await waitReceipt(pausedExpiry.commandId, 'accepted');
  evidence.pausedExpiry = await waitReceipt(pausedExpiry.commandId, 'cancelled');
  assert.equal(evidence.pausedExpiry.body.reason, 'TTL_EXPIRED');
  assert.equal(evidence.pausedExpiry.body.actionId, null);
  let seq = 0;
  const sourceEpoch = id + '-source';
  const fact = (type, data, ids = {}) => ({ specVersion: '1.0', source: 'fake:h4a', sourceEpoch, sequence: ++seq, eventId: `${id}-e-${seq}`, worldId: scope.worldId, actorId: 'harness-observation', sessionId: 'session-h4a', occurredAt: new Date().toISOString(), type, data, ...ids });
  const batch = { apiVersion: 'h5a.1', scope, batchId: id + '-working', events: [fact('presence.heartbeat', { status: 'alive' }), fact('run.started', {}, { runId: id + '-run' }), fact('tool.started', { toolCallId: id + '-tool', activityClass: 'coding' }, { runId: id + '-run' })] };
  evidence.batch = await post('events/batch', batch); assert.equal(evidence.batch.status, 202);
  await page.waitForFunction(() => window.__h5.snapshot().observation.state === 'working');
  await step(1.8);
  const working = await sample('working-standing-placeholder');
  assert.equal(working.status.body.observation.state, 'working'); assert.equal(working.status.body.desiredGoal, 'converse');
  assert.equal(working.browser.diagnostics.runtime.goalId, 'converse');
  assert.equal(working.status.body.actual.posture, 'standing');
  const second = { ...command, commandId: id + '-disconnect', issuedAtWallMs: Date.now() };
  evidence.second = await post('commands', second); await waitReceipt(second.commandId, 'accepted');
  await step(.1); await waitReceipt(second.commandId, 'started');
  await page.evaluate(() => window.__h5.disconnect());
  await step(.8);
  evidence.afterDisconnect = await read('commands/' + second.commandId);
  evidence.offline = await read('status');
  assert.notEqual(evidence.afterDisconnect.body.status, 'succeeded');
  assert.equal(evidence.offline.body.connection, 'offline');
  const safe = await sample('disconnect-safe-exit-not-service-success');
  assert.equal(safe.browser.diagnostics.runtime.action, null);
  evidence.newWhileOffline = await post('commands', { ...second, commandId: id + '-offline' }); assert.equal(evidence.newWhileOffline.status, 503);
  evidence.readSnapshot = await read(`snapshot?worldId=${scope.worldId}&actorId=${scope.actorId}`); assert.equal(evidence.readSnapshot.status, 200); assert.equal(evidence.readSnapshot.body.connection, 'offline'); assert.equal(evidence.readSnapshot.body.actual.posture, 'unknown');
  assert(evidence.websocket.some(row => row.handshakeStatus === 101));
  assert.deepEqual(evidence.errors, []);
  evidence.status = 'ready_for_review';
} catch (error) { evidence.failure = String(error); process.exitCode = 1; }
finally {
  if (page) evidence.finalBrowser = await page.evaluate(() => window.__h5 ? ({ hops: window.__h5.hops(), trace: window.__h5.trace(), snapshot: window.__h5.snapshot(), diagnostics: window.__h5.diagnostics() }) : null).catch(() => null);
  await browser.close();
  writeFileSync(output, JSON.stringify(evidence, null, 2) + '\n', { flag: 'wx' });
  console.log(JSON.stringify({ path: output.pathname, sha256: sha(readFileSync(output)), status: evidence.status, failure: evidence.failure, rows: evidence.rows.map(row => row.name) }));
}
